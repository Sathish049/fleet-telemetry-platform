"""Fleet API: read-only views of the fleet plus alert acknowledgement.

Run locally:  uvicorn app.main:app --reload
Docs:         http://localhost:8000/docs  (Swagger UI generated by FastAPI)
"""

from __future__ import annotations

import time
from datetime import datetime
from functools import lru_cache

from fastapi import Depends, FastAPI, HTTPException, Query, Request, Response
from fastapi.middleware.cors import CORSMiddleware
from prometheus_client import CONTENT_TYPE_LATEST, Counter, Histogram, generate_latest
from pydantic import BaseModel

from .repository import FleetRepository, make_engine

app = FastAPI(title="Fleet Telemetry API", version="1.0.0")
app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["GET", "POST"], allow_headers=["*"])

REQUESTS = Counter("api_requests_total", "HTTP requests", ["method", "route", "status"])
LATENCY = Histogram("api_request_seconds", "HTTP request latency", ["route"])


@app.middleware("http")
async def record_metrics(request: Request, call_next):
    start = time.perf_counter()
    response = await call_next(request)
    route = request.scope.get("route")
    path = route.path if route else "unmatched"  # use the template, not the raw URL, to keep labels bounded
    REQUESTS.labels(request.method, path, response.status_code).inc()
    LATENCY.labels(path).observe(time.perf_counter() - start)
    return response


@lru_cache
def get_repo() -> FleetRepository:
    return FleetRepository(make_engine())


# ---------- Response models (they also document the API in /docs) ----------

class Summary(BaseModel):
    total_vehicles: int
    online_vehicles: int
    driving_vehicles: int
    avg_battery_pct: float | None
    low_battery_vehicles: int
    open_alerts: int
    readings_last_minute: int
    generated_at: datetime


class Vehicle(BaseModel):
    vehicle_id: str
    ts: datetime
    speed_kph: float
    battery_pct: float
    temp_c: float
    lat: float
    lng: float
    status: str
    open_alerts: int


class HistoryPoint(BaseModel):
    ts: datetime
    speed_kph: float
    battery_pct: float
    temp_c: float


class Alert(BaseModel):
    id: int
    vehicle_id: str
    ts: datetime
    alert_type: str
    value: float
    message: str
    acknowledged: bool


# ---------- Routes ----------

@app.get("/api/health")
def health(repo: FleetRepository = Depends(get_repo)):
    try:
        repo.ping()
    except Exception as exc:  # noqa: BLE001 - report any DB failure as unhealthy
        raise HTTPException(status_code=503, detail=f"database unavailable: {exc}") from exc
    return {"status": "ok"}


@app.get("/api/fleet/summary", response_model=Summary)
def fleet_summary(repo: FleetRepository = Depends(get_repo)):
    return repo.summary()


@app.get("/api/vehicles", response_model=list[Vehicle])
def list_vehicles(repo: FleetRepository = Depends(get_repo)):
    return repo.vehicles()


@app.get("/api/vehicles/{vehicle_id}", response_model=Vehicle)
def get_vehicle(vehicle_id: str, repo: FleetRepository = Depends(get_repo)):
    v = repo.vehicle(vehicle_id)
    if v is None:
        raise HTTPException(status_code=404, detail="vehicle not found")
    return v


@app.get("/api/vehicles/{vehicle_id}/history", response_model=list[HistoryPoint])
def vehicle_history(
    vehicle_id: str,
    minutes: int = Query(15, ge=1, le=7 * 24 * 60),
    max_points: int = Query(300, ge=10, le=2000),
    repo: FleetRepository = Depends(get_repo),
):
    return repo.history(vehicle_id, minutes, max_points)


@app.get("/api/alerts", response_model=list[Alert])
def list_alerts(
    status: str = Query("open", pattern="^(open|all)$"),
    limit: int = Query(50, ge=1, le=500),
    vehicle_id: str | None = None,
    repo: FleetRepository = Depends(get_repo),
):
    return repo.alerts(open_only=(status == "open"), limit=limit, vehicle_id=vehicle_id)


@app.post("/api/alerts/{alert_id}/ack")
def acknowledge_alert(alert_id: int, repo: FleetRepository = Depends(get_repo)):
    if not repo.acknowledge(alert_id):
        raise HTTPException(status_code=404, detail="alert not found")
    return {"id": alert_id, "acknowledged": True}


@app.get("/metrics", include_in_schema=False)
def metrics():
    return Response(generate_latest(), media_type=CONTENT_TYPE_LATEST)
